// Package codegen lowers IR into ordinary Go functions and structs.
package codegen

import (
	"fmt"
	"go/format"
	"strconv"
	"strings"

	"github.com/katsuakikureyama/GoHP/internal/ir"
	"github.com/katsuakikureyama/GoHP/internal/semantic"
)

type generator struct {
	p       ir.Program
	b       strings.Builder
	funcs   map[string]int
	classes map[string]bool
	methods map[string]bool
	serial  int
}

func name(s string) string { return strings.ToLower(s) }
func Generate(p ir.Program) ([]byte, error) {
	out, _, err := GenerateWithMap(p)
	return out, err
}

// GenerateWithMap returns formatted Go and a statement-level map of those exact bytes.
func GenerateWithMap(p ir.Program) (out []byte, sourceMap SourceMap, err error) {
	defer func() {
		if e := recover(); e != nil {
			if x, ok := e.(error); ok {
				out, sourceMap = nil, SourceMap{}
				err = x
			} else {
				panic(e)
			}
		}
	}()
	g := &generator{p: p, funcs: map[string]int{}, classes: map[string]bool{}, methods: map[string]bool{}}
	if p.Version != ir.Version {
		return nil, SourceMap{}, fmt.Errorf("IR001: unsupported IR version %q", p.Version)
	}
	if err := semantic.Validate(p); err != nil {
		return nil, SourceMap{}, err
	}
	for _, f := range p.Functions {
		n := name(f.Name)
		if _, ok := g.funcs[n]; ok || n == "count" {
			g.fail(f.Line, "duplicate or reserved function "+n)
		}
		g.funcs[n] = len(f.Params)
	}
	for _, c := range p.Classes {
		n := name(c.Name)
		if g.classes[n] {
			g.fail(1, "duplicate class "+n)
		}
		g.classes[n] = true
		seen := map[string]bool{}
		for _, f := range c.Methods {
			m := name(f.Name)
			if strings.HasPrefix(m, "__") {
				g.fail(f.Line, "magic methods unsupported")
			}
			if seen[m] {
				g.fail(f.Line, "duplicate method")
			}
			seen[m] = true
			g.methods[m] = true
		}
		props := map[string]bool{}
		for _, v := range c.Properties {
			if props[v.Name] {
				g.fail(1, "duplicate property")
			}
			props[v.Name] = true
		}
	}
	g.emit("// Code generated by GoHP IR %s, PHP target %s. DO NOT EDIT.\npackage main\nimport rt %q\nvar _ = rt.Clone\n", p.Version, p.PHPVersion, "github.com/katsuakikureyama/GoHP/runtime")
	for _, f := range p.Functions {
		g.function(f, "")
	}
	for _, c := range p.Classes {
		g.emit("type C_%s struct {\n", name(c.Name))
		for _, v := range c.Properties {
			g.emit("P_%s any\n", v.Name)
		}
		g.emit("}\nfunc New_%s() any { return &C_%s{", name(c.Name), name(c.Name))
		for _, v := range c.Properties {
			g.emit("P_%s: %s,", v.Name, g.expr(v.Value, map[string]bool{}))
		}
		g.emit("} }\n")
		g.emit("func (self *C_%s) Get(k string) any { switch k {", name(c.Name))
		for _, v := range c.Properties {
			g.emit("case %q: return rt.Clone(self.P_%s)\n", v.Name, v.Name)
		}
		g.emit("}; panic(\"undefined property\") }\n")
		for _, f := range c.Methods {
			g.function(f, c.Name)
		}
	}
	g.emit("func main(){ v:=map[string]any{}; _=v\n")
	g.stmts(p.Body, map[string]bool{}, false)
	g.emit("}\n")
	out, err = format.Source([]byte(g.b.String()))
	if err != nil {
		return nil, SourceMap{}, err
	}
	sourceMap, err = mapStatements(out)
	if err != nil {
		return nil, SourceMap{}, err
	}
	return out, sourceMap, nil
}
func (g *generator) emit(s string, a ...any)   { fmt.Fprintf(&g.b, s, a...) }
func (g *generator) fail(line int, msg string) { panic(fmt.Errorf("PHP004 line %d: %s", line, msg)) }
func (g *generator) function(f ir.Function, c string) {
	if c == "" {
		g.emit("func F_%s(args ...any) any {\n", name(f.Name))
	} else {
		g.emit("func (self *C_%s) M_%s(args ...any) any {\n", name(c), name(f.Name))
	}
	g.emit("rt.Args(args,%d)\nv:=map[string]any{}; _=v\n", len(f.Params))
	scope := map[string]bool{}
	if c != "" {
		scope["this"] = true
		g.emit("v[\"this\"]=self\n")
	}
	for i, n := range f.Params {
		if scope[n] || n == "this" || n == "GLOBALS" {
			g.fail(f.Line, "duplicate or reserved parameter "+n)
		}
		scope[n] = true
		g.emit("v[%q]=rt.Clone(args[%d])\n", n, i)
	}
	g.stmts(f.Body, scope, true)
	if len(f.Body) == 0 || f.Body[len(f.Body)-1].Kind != "return" {
		g.emit("return nil\n")
	}
	g.emit("}\n")
}
func (g *generator) stmts(ss []ir.Stmt, scope map[string]bool, inFunc bool) {
	for _, s := range ss {
		g.emit("// gohp:begin %d\n", s.Line)
		switch s.Kind {
		case "assign":
			if s.Name == "this" || s.Name == "GLOBALS" || strings.HasPrefix(s.Name, "_") {
				g.fail(s.Line, "reserved/global variable unsupported")
			}
			e := g.expr(s.Expr, scope)
			scope[s.Name] = true
			g.emit("v[%q]=rt.Clone(%s)\n", s.Name, e)
		case "echo":
			g.emit("rt.Echo(%s)\n", g.expr(s.Expr, scope))
		case "return":
			if !inFunc {
				g.fail(s.Line, "top-level return unsupported")
			}
			g.emit("return rt.Clone(%s)\n", g.expr(s.Expr, scope))
		case "foreach":
			if s.Value == "this" || s.Key == "this" || s.Key != "" && s.Key == s.Value {
				g.fail(s.Line, "unsupported foreach bindings")
			}
			e := g.expr(s.Expr, scope)
			g.serial++
			n := g.serial
			g.emit("for _, entry%d := range rt.Entries(%s) {\n", n, e)
			inner := map[string]bool{}
			for k, v := range scope {
				inner[k] = v
			}
			if s.Key != "" {
				g.emit("v[%q]=entry%d.Key\n", s.Key, n)
				inner[s.Key] = true
			}
			g.emit("v[%q]=rt.Clone(entry%d.Value)\n", s.Value, n)
			inner[s.Value] = true
			g.stmts(s.Body, inner, inFunc)
			g.emit("}\n")
		default:
			g.fail(s.Line, "unsupported IR statement "+s.Kind)
		}
		g.emit("// gohp:end\n")
	}
}
func (g *generator) expr(e ir.Expr, scope map[string]bool) string {
	args := func(es []ir.Expr) string {
		var a []string
		for _, x := range es {
			a = append(a, g.expr(x, scope))
		}
		return strings.Join(a, ",")
	}
	switch e.Kind {
	case "int":
		return "int64(" + e.Text + ")"
	case "string":
		return strconv.Quote(e.Text)
	case "bool":
		return e.Text
	case "null":
		return "nil"
	case "var":
		if !scope[e.Text] {
			g.fail(e.Line, "undefined or conditionally assigned variable $"+e.Text)
		}
		return "v[" + strconv.Quote(e.Text) + "]"
	case "binary":
		op := "Add"
		if e.Text == "." {
			op = "Concat"
		} else if e.Text != "+" {
			g.fail(e.Line, "unsupported operator")
		}
		return "rt." + op + "(" + args(e.Args) + ")"
	case "array":
		var a []string
		for _, pair := range e.Args {
			k := pair.Args[0]
			key := "nil"
			if k.Kind != "auto" {
				if k.Kind != "int" && k.Kind != "string" {
					g.fail(k.Line, "array keys must be integer/string literals")
				}
				key = g.expr(k, scope)
			}
			a = append(a, "rt.Entry{Key:"+key+",Value:"+g.expr(pair.Args[1], scope)+"}")
		}
		return "rt.NewArray(" + strings.Join(a, ",") + ")"
	case "index":
		return "rt.Get(" + args(e.Args) + ")"
	case "call":
		n := name(e.Text)
		if n == "count" {
			if len(e.Args) != 1 {
				g.fail(e.Line, "count expects one argument")
			}
			return "rt.Count(" + args(e.Args) + ")"
		}
		arity, ok := g.funcs[n]
		if !ok {
			g.fail(e.Line, "unsupported function "+n)
		}
		if len(e.Args) != arity {
			g.fail(e.Line, "unsupported argument count for "+n)
		}
		return "F_" + n + "(" + args(e.Args) + ")"
	case "new":
		if !g.classes[name(e.Text)] {
			g.fail(e.Line, "unknown class "+e.Text)
		}
		return "New_" + name(e.Text) + "()"
	case "property":
		return "(" + g.expr(e.Args[0], scope) + ").(interface{Get(string) any}).Get(" + strconv.Quote(e.Text) + ")"
	case "method":
		n := name(e.Text)
		if !g.methods[n] {
			g.fail(e.Line, "unknown method "+n)
		}
		return "(" + g.expr(e.Args[0], scope) + ").(interface{M_" + n + "(...any) any}).M_" + n + "(" + args(e.Args[1:]) + ")"
	}
	g.fail(e.Line, "unsupported IR expression "+e.Kind)
	return ""
}
