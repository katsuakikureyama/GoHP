// Package codegen lowers IR into ordinary Go functions and structs.
package codegen

import (
	"fmt"
	"go/format"
	"strconv"
	"strings"

	"github.com/katsuakikureyama/GoHP/internal/ir"
	"github.com/katsuakikureyama/GoHP/internal/phpversion"
	"github.com/katsuakikureyama/GoHP/internal/semantic"
)

type generator struct {
	p             ir.Program
	b             strings.Builder
	funcs         map[string]int
	minimum       map[string]int
	classes       map[string]bool
	methods       map[string]bool
	serial        int
	sourceID      string
	sourceIndices map[string]int
	// Dead tails are still traversed for codegen-only validation, not emitted.
	suppress bool
	// Emit execution-aware calls only for programs containing stateful builtins.
	execution bool
	// Only closed scalar bodies with proven scalar entry values use owned storage.
	scalarFrame bool
	// Shared-value lane: scalar-guarded flat-array scopes and bounded control flow.
	ownedValues bool
}

func name(s string) string { return strings.ToLower(s) }
func Generate(p ir.Program) ([]byte, error) {
	out, _, err := GenerateWithMap(p)
	return out, err
}

// GenerateWithMap returns formatted Go and a statement-level map of those exact bytes.
func GenerateWithMap(p ir.Program) (out []byte, sourceMap SourceMap, err error) {
	defer func() {
		if e := recover(); e != nil {
			if x, ok := e.(error); ok {
				out, sourceMap = nil, SourceMap{}
				err = x
			} else {
				panic(e)
			}
		}
	}()
	g := &generator{p: p, funcs: map[string]int{}, classes: map[string]bool{}, methods: map[string]bool{}}
	g.minimum = map[string]int{}
	if p.Version != ir.Version {
		return nil, SourceMap{}, fmt.Errorf("IR001: unsupported IR version %q", p.Version)
	}
	if err := semantic.Validate(p); err != nil {
		return nil, SourceMap{}, err
	}
	g.sourceIndices = map[string]int{}
	for i, source := range p.Sources {
		g.sourceIndices[source.ID] = i + 1
	}
	g.execution = usesExecution(p)
	for _, f := range p.Functions {
		g.sourceID = f.SourceID
		n := name(f.Name)
		if n == "substr" || n == "gettype" {
			g.fail(f.Line, "reserved function "+n)
		}
		if n == "array_key_first" || n == "array_key_last" || n == "array_reverse" || n == "array_merge" || n == "array_slice" || n == "array_push" {
			g.fail(f.Line, "reserved function "+n)
		}
		if n == "empty" || n == "continue" || n == "break" || n == "while" {
			g.fail(f.Line, "reserved language construct "+n)
		}
		if n == "str_contains" || n == "str_starts_with" || n == "strtok" {
			g.fail(f.Line, "reserved function "+n)
		}
		if _, ok := g.funcs[n]; ok || n == "in_array" || n == "isset" || n == "count" || n == "strlen" || n == "array_keys" || n == "array_values" || n == "array_key_exists" || n == "array_is_list" || n == "rtrim" || n == "is_bool" || n == "is_string" || n == "is_null" || n == "is_int" || n == "is_array" || n == "is_object" || n == "strtolower" || n == "strcasecmp" || n == "sprintf" || n == "str_replace" || n == "stripslashes" || n == "array_map" || n == "addslashes" {
			g.fail(f.Line, "duplicate or reserved function "+n)
		}
		g.funcs[n] = len(f.Params)
		g.minimum[n] = len(f.Params) - f.OptionalNullParams
	}
	for _, c := range p.Classes {
		g.sourceID = c.SourceID
		n := name(c.Name)
		if g.classes[n] {
			line := 1
			if c.SourceID != "" {
				line = c.Line
			}
			g.fail(line, "duplicate class "+n)
		}
		g.classes[n] = true
		seen := map[string]bool{}
		for _, f := range c.Methods {
			m := name(f.Name)
			if strings.HasPrefix(m, "__") && m != "__construct" {
				g.fail(f.Line, "magic methods unsupported")
			}
			if seen[m] {
				g.fail(f.Line, "duplicate method")
			}
			seen[m] = true
			if m != "__construct" {
				g.methods[m] = true
			}
		}
		props := map[string]bool{}
		for _, v := range c.Properties {
			if props[v.Name] {
				line := 1
				if c.SourceID != "" {
					line = v.Value.Line
				}
				g.fail(line, "duplicate property")
			}
			props[v.Name] = true
		}
	}
	g.emit("// Code generated by GoHP IR %s, PHP target %s. DO NOT EDIT.\n", p.Version, p.PHPVersion)
	if p.RegexProfile != "" {
		g.emit("// Experimental regex profile: %s (requires optional native backend).\n", p.RegexProfile)
	}
	g.emit("package main\nimport rt %q\nvar _ = rt.Clone\n", "github.com/katsuakikureyama/GoHP/runtime")
	for _, f := range p.Functions {
		g.sourceID = f.SourceID
		g.function(f, "")
	}
	for _, c := range p.Classes {
		g.sourceID = c.SourceID
		hasConstructor := false
		for _, method := range c.Methods {
			if strings.EqualFold(method.Name, "__construct") {
				hasConstructor = true
			}
		}
		g.emit("type C_%s struct {\n", name(c.Name))
		for _, v := range c.Properties {
			g.emit("P_%s any\n", v.Name)
		}
		if g.execution {
			g.emit("}\nfunc New_%s(args ...any) any { return NewContext_%s(&rt.Execution{},args...) }\n", name(c.Name), name(c.Name))
			g.emit("func NewContext_%s(execution *rt.Execution,args ...any) any { rt.RequireExecution(execution)\n", name(c.Name))
		} else {
			g.emit("}\nfunc New_%s(args ...any) any {", name(c.Name))
		}
		if !hasConstructor {
			g.emit("rt.Args(args,0)\n")
		}
		g.emit("self := &C_%s{", name(c.Name))
		for _, v := range c.Properties {
			g.emit("P_%s: %s,", v.Name, g.expr(v.Value, map[string]bool{}))
		}
		g.emit("}\n")
		if hasConstructor {
			if g.execution {
				g.emit("self.MContext___construct(execution,args...)\n")
			} else {
				g.emit("self.M___construct(args...)\n")
			}
		}
		g.emit("return self\n}\n")
		g.emit("func (self *C_%s) Get(k string) any { switch k {", name(c.Name))
		for _, v := range c.Properties {
			g.emit("case %q: return rt.Clone(self.P_%s)\n", v.Name, v.Name)
		}
		g.emit("}; panic(\"undefined property\") }\n")
		g.emit("func (self *C_%s) PHPPropertyLookup(k string) (any,bool) { switch k {", name(c.Name))
		for _, property := range c.Properties {
			g.emit("case %q: return self.P_%s,true\n", property.Name, property.Name)
		}
		g.emit("}; return nil,false }\n")
		g.emit("func (self *C_%s) Set(k string, value any) { switch k {", name(c.Name))
		for _, v := range c.Properties {
			g.emit("case %q: self.P_%s = rt.Clone(value); return\n", v.Name, v.Name)
		}
		g.emit("}; panic(\"undefined property assignment\") }\n")
		g.emit("func (self *C_%s) PHPObject() bool { return self != nil }\n", name(c.Name))
		g.emit("func (self *C_%s) PHPProperties() rt.Array { return rt.NewArray(", name(c.Name))
		for _, property := range c.Properties {
			g.emit("rt.Entry{Key:%q,Value:self.P_%s},", property.Name, property.Name)
		}
		g.emit(") }\n")
		for _, f := range c.Methods {
			g.function(f, c.Name)
		}
	}
	g.sourceID = ""
	g.emit("func main(){ v:=map[string]any{}; _=v\n")
	if g.execution {
		g.emit("execution := &rt.Execution{}; _=execution\n")
	}
	g.stmts(p.Body, map[string]bool{}, false, "")
	g.emit("}\n")
	out, err = format.Source([]byte(g.b.String()))
	if err != nil {
		return nil, SourceMap{}, err
	}
	sourceMap, err = mapStatements(out, p.Sources...)
	if err != nil {
		return nil, SourceMap{}, err
	}
	return out, sourceMap, nil
}
func (g *generator) emit(s string, a ...any) {
	if !g.suppress {
		fmt.Fprintf(&g.b, s, a...)
	}
}
func (g *generator) fail(line int, msg string) {
	panic(ir.WithSource(fmt.Errorf("PHP004 line %d: %s", line, msg), g.sourceID))
}
func (g *generator) function(f ir.Function, c string) {
	previousSource := g.sourceID
	if f.SourceID != "" {
		g.sourceID = f.SourceID
	}
	defer func() { g.sourceID = previousSource }()
	previousFrame := g.scalarFrame
	previousOwned := g.ownedValues
	g.scalarFrame = c == "" && scalarFrameParameters(f) && f.ReturnType != "array" && scalarFrameBody(f.Body)
	ownedLocals, owned := ownedValueLocals(f)
	g.ownedValues = c == "" && !g.scalarFrame && owned
	defer func() { g.scalarFrame, g.ownedValues = previousFrame, previousOwned }()
	if g.execution && c == "" {
		g.emit("func F_%s(args ...any) any { return FContext_%s(&rt.Execution{}, args...) }\n", name(f.Name), name(f.Name))
		g.emit("func FContext_%s(execution *rt.Execution, args ...any) any { rt.RequireExecution(execution)\n", name(f.Name))
	} else if g.execution {
		g.emit("func (self *C_%s) M_%s(args ...any) any { return self.MContext_%s(&rt.Execution{}, args...) }\n", name(c), name(f.Name), name(f.Name))
		g.emit("func (self *C_%s) MContext_%s(execution *rt.Execution, args ...any) any { rt.RequireExecution(execution)\n", name(c), name(f.Name))
	} else if c == "" {
		g.emit("func F_%s(args ...any) any {\n", name(f.Name))
	} else {
		g.emit("func (self *C_%s) M_%s(args ...any) any {\n", name(c), name(f.Name))
	}
	if f.OptionalNullParams != 0 {
		g.emit("args=rt.NullDefaultArgs(args,%d,%d)\n", len(f.Params)-f.OptionalNullParams, len(f.Params))
	} else {
		g.emit("rt.Args(args,%d)\n", len(f.Params))
	}
	if g.scalarFrame {
		g.emit("v:=rt.NewScalarFrame(); defer v.Close()\n")
	} else if g.ownedValues {
		g.emit("v:=map[string]*rt.ValueSlot{}; _=v\n")
		for _, local := range ownedLocals {
			g.emit("v[%q]=&rt.ValueSlot{}; defer v[%q].Close()\n", local, local)
		}
	} else {
		g.emit("v:=map[string]any{}; _=v\n")
	}
	scope := map[string]bool{}
	if c != "" {
		scope["this"] = true
		g.emit("v[\"this\"]=self\n")
	}
	for i, n := range f.Params {
		if scope[n] || n == "this" || n == "GLOBALS" {
			g.fail(f.Line, "duplicate or reserved parameter "+n)
		}
		scope[n] = true
		if g.scalarFrame {
			// Selection proves a scalar annotation for every parameter; the
			// runtime entry guard runs before storing the value or entering PHP.
			g.emit("v.Write(%q,rt.ScalarParameter(args[%d],%q))\n", n, i, f.ParamTypes[i])
		} else if g.ownedValues {
			// The same exact scalar entry proof excludes host arrays. All slot
			// cleanup is already registered if this or a later guard panics.
			g.emit("v[%q].Write(rt.ScalarParameter(args[%d],%q))\n", n, i, f.ParamTypes[i])
		} else if len(f.ParamTypes) != 0 && f.ParamTypes[i] == "array" {
			g.emit("v[%q]=rt.ArrayParameter(args[%d])\n", n, i)
		} else if len(f.ParamTypes) != 0 && f.ParamTypes[i] == "callable" {
			g.emit("v[%q]=rt.CallableParameter(args[%d])\n", n, i)
		} else if len(f.ParamTypes) != 0 && strings.HasPrefix(f.ParamTypes[i], "class:") {
			class := strings.TrimPrefix(f.ParamTypes[i], "class:")
			g.serial++
			g.emit("classArg%d,classOK%d:=args[%d].(*C_%s)\n", g.serial, g.serial, i, class)
			g.emit("if !classOK%d || classArg%d==nil { panic(%q) }\n", g.serial, g.serial, "class parameter requires "+class+" object")
			g.emit("v[%q]=classArg%d\n", n, g.serial)
		} else if len(f.ParamTypes) != 0 && f.ParamTypes[i] != "" {
			g.emit("v[%q]=rt.ScalarParameter(args[%d],%q)\n", n, i, f.ParamTypes[i])
		} else {
			g.emit("v[%q]=rt.Clone(args[%d])\n", n, i)
		}
	}
	g.stmts(f.Body, scope, true, f.ReturnType)
	if len(f.Body) == 0 || f.Body[len(f.Body)-1].Kind != "return" {
		if f.ReturnType == "array" {
			g.emit("return rt.ArrayReturn(nil)\n")
		} else if f.ReturnType == "bool" {
			g.emit("return rt.BoolReturn(nil)\n")
		} else {
			g.emit("return nil\n")
		}
	}
	g.emit("}\n")
}
func (g *generator) stmts(ss []ir.Stmt, scope map[string]bool, inFunc bool, returnType string) {
	previous := g.suppress
	previousSource := g.sourceID
	defer func() { g.suppress = previous; g.sourceID = previousSource }()
	for _, s := range ss {
		if s.SourceID != "" {
			g.sourceID = s.SourceID
		}
		if len(g.p.Sources) != 0 {
			g.emit("// gohp:begin %d %d\n", s.Line, g.sourceIndices[g.sourceID])
		} else {
			g.emit("// gohp:begin %d\n", s.Line)
		}
		switch s.Kind {
		case "array_push":
			g.arrayPush(s, scope)
		case "assign_nested_property", "assign_nested_property_append", "assign_nested_property_concat":
			g.nestedProperty(s, scope)
		case "switch":
			g.stringSwitch(s, scope, inFunc, returnType)
		case "list_assign":
			// ListValues evaluates/validates the entire positional snapshot
			// before replacing any local, including an alias of the RHS.
			g.serial++
			values := fmt.Sprintf("list%d", g.serial)
			g.emit("%s := rt.ListValues(%s,%d)\n", values, g.expr(s.Expr, scope), len(s.Target.Args))
			for i, local := range s.Target.Args {
				g.emit("v[%q]=%s[%d]\n", local.Text, values, i)
				scope[local.Text] = true
			}
		case "preg_match_local":
			// Semantic validation proves a straight-line, initialized-null bare
			// output local and pure, non-aliasing inputs. This statement excludes
			// scalar-frame and flat owned-value lanes for the entire scope.
			g.serial++
			result := fmt.Sprintf("preg%d", g.serial)
			// Snapshot both value inputs, in source order, before the runtime
			// guard/engine call or either output-local publication.
			g.emit("%sSubject := %s\n", result, g.expr(s.Expr.Args[1], scope))
			g.emit("%sOffset := %s\n", result, g.expr(s.Expr.Args[2], scope))
			g.emit("%s := execution.PregMatch83Local(%s,%s,%s)\n", result,
				g.expr(s.Expr.Args[0], scope), result+"Subject", result+"Offset")
			g.emit("v[%q]=rt.Clone(%s.Matches)\n", s.Target.Text, result)
			g.emit("v[%q]=%s.Return\n", s.Name, result)
			scope[s.Target.Text], scope[s.Name] = true, true
		case "call_stmt":
			// Evaluate once, retain callee/argument guards and discard only the
			// result. No echo, clone, assignment binding or truthiness conversion.
			g.emit("_ = %s\n", g.expr(s.Expr, scope))
		case "continue", "break":
			g.emit("%s\n", s.Kind) // Enclosing loop and payload checked by semantic.
		case "assign":
			if s.Name == "this" || s.Name == "GLOBALS" || strings.HasPrefix(s.Name, "_") {
				g.fail(s.Line, "reserved/global variable unsupported")
			}
			if g.ownedValues {
				g.ownedValueAssignment(s.Name, s.Expr, scope)
			} else if g.scalarFrame {
				e := g.expr(s.Expr, scope)
				g.emit("v.Write(%q,rt.Clone(%s))\n", s.Name, e)
			} else {
				e := g.expr(s.Expr, scope)
				g.emit("v[%q]=rt.Clone(%s)\n", s.Name, e)
			}
			scope[s.Name] = true
		case "assign_property", "assign_property_append":
			// Unknown locals use the same explicit writable-object protocol as
			// nested paths. Evaluate RHS once before resolving/checking the slot;
			// append reads the current property only after RHS side effects.
			receiver := g.expr(s.Target.Args[0], scope)
			value := g.expr(s.Expr, scope)
			operation := "Assign"
			if s.Kind == "assign_property_append" {
				operation = "Append"
			}
			g.emit("{ value := any(%s); target := rt.ResolveProperty(%s,%q); target.%s(value) }\n", value, receiver, s.Target.Text, operation)
		case "assign_index":
			root := s.Target.Args[0].Text // Shape validated before generation.
			if root == "this" || root == "GLOBALS" || strings.HasPrefix(root, "_") {
				g.fail(s.Line, "reserved/global variable unsupported")
			}
			base := g.expr(s.Target.Args[0], scope)
			key := g.expr(s.Target.Args[1], scope)
			value := g.expr(s.Expr, scope)
			if g.ownedValues {
				g.emit("{ key := any(%s); value := any(%s); v[%q].ArrayWrite(key,value) }\n", key, value, root)
			} else {
				g.emit("v[%q]=rt.ArraySet(%s,%s,%s)\n", root, base, key, value)
			}
		case "assign_append":
			root := s.Target.Text // Variable-only shape validated before generation.
			if root == "this" || root == "GLOBALS" || strings.HasPrefix(root, "_") {
				g.fail(s.Line, "reserved/global variable unsupported")
			}
			base := g.expr(s.Target, scope)
			value := g.expr(s.Expr, scope)
			if g.ownedValues {
				g.emit("{ value := any(%s); v[%q].ArrayAppend(value) }\n", value, root)
			} else {
				g.emit("v[%q]=rt.ArrayAppend(%s,%s)\n", root, base, value)
			}
		case "echo":
			g.emit("rt.Echo(%s)\n", g.expr(s.Expr, scope))
		case "return":
			if !inFunc {
				g.fail(s.Line, "top-level return unsupported")
			}
			var result string
			if g.ownedValues {
				result = g.ownedValueResult(s.Expr, scope)
			} else {
				result = g.expr(s.Expr, scope)
			}
			if returnType == "array" {
				g.emit("return rt.ArrayReturn(%s)\n", result)
			} else if returnType == "bool" {
				g.emit("return rt.BoolReturn(%s)\n", result)
			} else {
				g.emit("return rt.Clone(%s)\n", result)
			}
		case "if":
			g.emit("if rt.Bool(%s) {\n", g.expr(s.Expr, scope))
			inner := map[string]bool{}
			for k, v := range scope {
				inner[k] = v
			}
			g.stmts(s.Body, inner, inFunc, returnType)
			if s.ElseBody != nil {
				g.emit("} else {\n")
				other := map[string]bool{}
				for k, v := range scope {
					other[k] = v
				}
				g.stmts(s.ElseBody, other, inFunc, returnType)
			}
			g.emit("}\n")
		case "while":
			g.emit("for rt.Bool(%s) {\n", g.expr(s.Expr, scope))
			inner := map[string]bool{}
			for name, defined := range scope {
				inner[name] = defined
			}
			g.stmts(s.Body, inner, inFunc, returnType)
			g.emit("}\n")
		case "foreach":
			if s.Value == "this" || s.Key == "this" || s.Key != "" && s.Key == s.Value {
				g.fail(s.Line, "unsupported foreach bindings")
			}
			e := g.expr(s.Expr, scope)
			g.serial++
			n := g.serial
			g.emit("for _, entry%d := range rt.Entries(%s) {\n", n, e)
			inner := map[string]bool{}
			for k, v := range scope {
				inner[k] = v
			}
			if s.Key != "" {
				g.emit("v[%q]=entry%d.Key\n", s.Key, n)
				inner[s.Key] = true
			}
			g.emit("v[%q]=rt.Clone(entry%d.Value)\n", s.Value, n)
			inner[s.Value] = true
			g.stmts(s.Body, inner, inFunc, returnType)
			g.emit("}\n")
		default:
			g.fail(s.Line, "unsupported IR statement "+s.Kind)
		}
		g.emit("// gohp:end\n")
		if s.Kind == "continue" || s.Kind == "break" {
			g.suppress = true
		}
	}
}
func (g *generator) expr(e ir.Expr, scope map[string]bool) string {
	args := func(es []ir.Expr) string {
		var a []string
		for _, x := range es {
			a = append(a, g.expr(x, scope))
		}
		return strings.Join(a, ",")
	}
	switch e.Kind {
	case "arrow":
		inner := map[string]bool{}
		var bindings strings.Builder
		for i, param := range e.Params {
			inner[param] = true
			fmt.Fprintf(&bindings, "v[%q]=args[%d];", param, i)
		}
		// This function has a fresh local v, never the enclosing scope's map.
		// Invoke owns arity, argument copies and the returned-value copy.
		if g.execution {
			return fmt.Sprintf("rt.NewCallableWithExecution(%d,func(execution *rt.Execution,args ...any) any {v:=map[string]any{}; _=v; %s return %s})", len(e.Params), bindings.String(), g.expr(e.Args[0], inner))
		}
		return fmt.Sprintf("rt.NewCallable(%d,func(args ...any) any {v:=map[string]any{}; _=v; %s return %s})", len(e.Params), bindings.String(), g.expr(e.Args[0], inner))
	case "invoke":
		if g.execution {
			return "rt.InvokeWithExecution(execution," + args(e.Args) + ")"
		}
		return "rt.Invoke(" + args(e.Args) + ")"
	case "int":
		return "int64(" + e.Text + ")"
	case "version_constant":
		value, err := phpversion.VersionConstant(g.p.PHPVersion, e.Text)
		if err != nil {
			g.fail(e.Line, err.Error())
		}
		return "int64(" + strconv.FormatInt(value, 10) + ")"
	case "string":
		return strconv.Quote(e.Text)
	case "bool":
		return e.Text
	case "null":
		return "nil"
	case "var":
		if !scope[e.Text] {
			g.fail(e.Line, "undefined or conditionally assigned variable $"+e.Text)
		}
		if g.scalarFrame {
			return "v.Read(" + strconv.Quote(e.Text) + ")"
		}
		if g.ownedValues {
			return "v[" + strconv.Quote(e.Text) + "].Read()"
		}
		return "v[" + strconv.Quote(e.Text) + "]"
	case "ternary":
		if len(e.Args) != 3 {
			g.fail(e.Line, "ternary expects three operands")
		}
		// A closure keeps the condition single-evaluation and both arms lazy.
		return "(func() any { if rt.Bool(" + g.expr(e.Args[0], scope) + ") { return " + g.expr(e.Args[1], scope) + " }; return " + g.expr(e.Args[2], scope) + " }())"
	case "coalesce":
		root, keys, _ := ir.ArrayAddressParts(e.Args[0]) // Semantic validates the exact address shape.
		probe := append([]ir.Expr{root}, keys...)
		return "(func() any { value, present := rt.ArrayPathProbe(" + args(probe) + "); if present { return value }; return " + g.expr(e.Args[1], scope) + " }())"
	case "binary":
		if e.Text == "===" || e.Text == "!==" {
			other := -1
			if e.Args[0].Kind == "null" {
				other = 1
			} else if e.Args[1].Kind == "null" {
				other = 0
			}
			if other >= 0 {
				probe := "rt.IsNull(" + g.expr(e.Args[other], scope) + ")"
				if e.Text == "!==" {
					return "(!" + probe + ")"
				}
				return probe
			}
		}
		if e.Text == "&&" || e.Text == "||" {
			// Go's logical operators preserve PHP's left-to-right short circuit.
			return "(rt.Bool(" + g.expr(e.Args[0], scope) + ") " + e.Text + " rt.Bool(" + g.expr(e.Args[1], scope) + "))"
		}
		if e.Text == "===" {
			return "rt.Identical(" + args(e.Args) + ")"
		}
		if e.Text == "!==" {
			return "(!rt.Identical(" + args(e.Args) + "))"
		}
		op := "Add"
		if e.Text == "." {
			op = "Concat"
		} else if e.Text == "-" {
			op = "Subtract"
		} else if e.Text == "<" {
			op = "LessThan"
		} else if e.Text == ">" {
			op = "GreaterThan"
		} else if e.Text != "+" {
			g.fail(e.Line, "unsupported operator")
		}
		return "rt." + op + "(" + args(e.Args) + ")"
	case "bool_cast":
		return "rt.Bool(" + args(e.Args) + ")"
	case "not":
		return "(!rt.Bool(" + args(e.Args) + "))"
	case "array":
		var a []string
		for _, pair := range e.Args {
			k := pair.Args[0]
			key := "nil"
			if k.Kind != "auto" {
				if k.Kind != "int" && k.Kind != "string" {
					g.fail(k.Line, "array keys must be integer/string literals")
				}
				key = g.expr(k, scope)
			}
			a = append(a, "rt.Entry{Key:"+key+",Value:"+g.expr(pair.Args[1], scope)+"}")
		}
		return "rt.NewArray(" + strings.Join(a, ",") + ")"
	case "index":
		return "rt.Get(" + args(e.Args) + ")"
	case "isset_index":
		return "rt.ArrayIsset(" + args(e.Args) + ")"
	case "isset_path":
		return "rt.ArrayPathIsset(" + args(e.Args) + ")"
	case "isset_var":
		return "rt.IssetValue(" + args(e.Args) + ")"
	case "isset_property":
		return "rt.PropertyIsset(" + args(e.Args) + ")"
	case "isset_multi":
		var operands []string
		for _, operand := range e.Args {
			operands = append(operands, g.expr(operand, scope))
		}
		return "(" + strings.Join(operands, " && ") + ")"
	case "empty_array":
		return "rt.ArrayEmpty(" + args(e.Args) + ")"
	case "empty_var":
		return "rt.VariableEmpty(" + args(e.Args) + ")"
	case "call":
		n := name(e.Text)
		if n == "preg_last_error" {
			return "execution.PregLastError83()"
		}
		if n == "strtok" {
			return "execution.Strtok(" + args(e.Args) + ")"
		}
		if (n == "array_any" || n == "array_all") && g.p.PHPVersion == "8.4" {
			// Validate has already proved a two-value, untyped named callback
			// with a bool return declaration; keep request-local state intact.
			callback := name(e.Args[1].Text)
			call := "F_" + callback + "(value,key)"
			if g.execution {
				call = "FContext_" + callback + "(execution,value,key)"
			}
			helper := "rt.ArrayAny"
			if n == "array_all" {
				helper = "rt.ArrayAll"
			}
			return helper + "(" + g.expr(e.Args[0], scope) + ", func(value, key any) any { return " + call + " })"
		}
		if n == "array_map" {
			if len(e.Args) != 2 || e.Args[0].Kind != "string" {
				g.fail(e.Line, "array_map expects a literal named callback and one array")
			}
			callback := name(e.Args[0].Text)
			if arity, ok := g.funcs[callback]; !ok || arity < 1 || g.minimum[callback] > 1 {
				g.fail(e.Line, "array_map callback must be a declared one-argument function")
			}
			if g.execution {
				return "rt.ArrayMap(func(value any) any { return FContext_" + callback + "(execution,value) }, " + g.expr(e.Args[1], scope) + ")"
			}
			return "rt.ArrayMap(func(value any) any { return F_" + callback + "(value) }, " + g.expr(e.Args[1], scope) + ")"
		}
		if n == "in_array" {
			if len(e.Args) != 3 || e.Args[2].Kind != "bool" || e.Args[2].Text != "true" {
				g.fail(e.Line, "in_array expects three arguments with literal true strictness")
			}
			return "rt.InArrayStrict(" + args(e.Args[:2]) + ")"
		}
		if n == "gettype" {
			if len(e.Args) != 1 {
				g.fail(e.Line, "gettype expects one argument")
			}
			return "rt.GetType(" + args(e.Args) + ")"
		}
		if n == "addslashes" {
			if len(e.Args) != 1 {
				g.fail(e.Line, "addslashes expects one argument")
			}
			return "rt.AddSlashes(" + args(e.Args) + ")"
		}
		if n == "stripslashes" {
			if len(e.Args) != 1 {
				g.fail(e.Line, "stripslashes expects one argument")
			}
			return "rt.StripSlashes(" + args(e.Args) + ")"
		}
		if n == "str_replace" {
			if len(e.Args) != 3 {
				g.fail(e.Line, "str_replace expects three arguments")
			}
			return "rt.StrReplace(" + args(e.Args) + ")"
		}
		if n == "sprintf" {
			if len(e.Args) != 2 {
				g.fail(e.Line, "sprintf expects two arguments")
			}
			return "rt.SprintfZeroPad(" + args(e.Args) + ")"
		}
		booleanBuiltins := map[string]string{"is_object": "IsObject", "is_null": "IsNull", "is_int": "IsInt", "is_bool": "IsBool", "is_string": "IsString", "is_array": "IsArray", "strtolower": "StrToLower"}
		if builtin, ok := booleanBuiltins[n]; ok {
			if len(e.Args) != 1 {
				g.fail(e.Line, n+" expects one argument")
			}
			return "rt." + builtin + "(" + args(e.Args) + ")"
		}
		if n == "count" {
			if len(e.Args) != 1 {
				g.fail(e.Line, "count expects one argument")
			}
			return "rt.Count(" + args(e.Args) + ")"
		}
		if n == "str_starts_with" {
			if len(e.Args) != 2 {
				g.fail(e.Line, "str_starts_with expects two arguments")
			}
			return "rt.StrStartsWith(" + args(e.Args) + ")"
		}
		if n == "str_contains" {
			if len(e.Args) != 2 {
				g.fail(e.Line, "str_contains expects two arguments")
			}
			return "rt.StrContains(" + args(e.Args) + ")"
		}
		if n == "strcasecmp" {
			if len(e.Args) != 2 {
				g.fail(e.Line, "strcasecmp expects two arguments")
			}
			return "rt.StrCaseCmp(" + args(e.Args) + ")"
		}
		if n == "strlen" {
			if len(e.Args) != 1 {
				g.fail(e.Line, "strlen expects one argument")
			}
			return "rt.Strlen(" + args(e.Args) + ")"
		}
		if n == "substr" {
			if len(e.Args) < 2 || len(e.Args) > 3 {
				g.fail(e.Line, "substr expects two or three arguments")
			}
			values := args(e.Args)
			if len(e.Args) == 2 {
				values += ",nil"
			}
			return "rt.Substr(" + values + ")"
		}
		if n == "array_keys" {
			if len(e.Args) != 1 {
				g.fail(e.Line, "array_keys expects one argument")
			}
			return "rt.ArrayKeys(" + args(e.Args) + ")"
		}
		if n == "array_values" {
			if len(e.Args) != 1 {
				g.fail(e.Line, "array_values expects one argument")
			}
			return "rt.ArrayValues(" + args(e.Args) + ")"
		}
		if n == "array_slice" {
			if len(e.Args) < 2 || len(e.Args) > 4 {
				g.fail(e.Line, "array_slice expects two to four arguments")
			}
			values := args(e.Args)
			if len(e.Args) == 2 {
				values += ", nil"
			}
			if len(e.Args) < 4 {
				values += ", false"
			}
			return "rt.ArraySlice(" + values + ")"
		}
		if n == "array_merge" {
			return "rt.ArrayMerge(" + args(e.Args) + ")"
		}
		if n == "array_reverse" {
			if len(e.Args) < 1 || len(e.Args) > 2 {
				g.fail(e.Line, "array_reverse expects one or two arguments")
			}
			values := args(e.Args)
			if len(e.Args) == 1 {
				values += ", false"
			}
			return "rt.ArrayReverse(" + values + ")"
		}
		if n == "array_key_first" {
			if len(e.Args) != 1 {
				g.fail(e.Line, "array_key_first expects one argument")
			}
			return "rt.ArrayKeyFirst(" + args(e.Args) + ")"
		}
		if n == "array_key_last" {
			if len(e.Args) != 1 {
				g.fail(e.Line, "array_key_last expects one argument")
			}
			return "rt.ArrayKeyLast(" + args(e.Args) + ")"
		}
		if n == "array_key_exists" {
			if len(e.Args) != 2 {
				g.fail(e.Line, "array_key_exists expects two arguments")
			}
			return "rt.ArrayKeyExists(" + args(e.Args) + ")"
		}
		if n == "array_is_list" {
			if len(e.Args) != 1 {
				g.fail(e.Line, "array_is_list expects one argument")
			}
			return "rt.ArrayIsList(" + args(e.Args) + ")"
		}
		if n == "rtrim" {
			if len(e.Args) != 2 {
				g.fail(e.Line, "rtrim expects two arguments")
			}
			if e.Args[1].Kind != "string" {
				g.fail(e.Line, "rtrim requires a string literal mask")
			}
			if strings.Contains(e.Args[1].Text, "..") {
				g.fail(e.Line, "rtrim character ranges unsupported")
			}
			return "rt.RTrim(" + g.expr(e.Args[0], scope) + "," + strconv.Quote(e.Args[1].Text) + ")"
		}
		arity, ok := g.funcs[n]
		if !ok {
			g.fail(e.Line, "unsupported function "+n)
		}
		if len(e.Args) > arity || len(e.Args) < g.minimum[n] {
			g.fail(e.Line, "unsupported argument count for "+n)
		}
		if g.execution {
			return "FContext_" + n + "(execution," + args(e.Args) + ")"
		}
		return "F_" + n + "(" + args(e.Args) + ")"
	case "new":
		if !g.classes[name(e.Text)] {
			g.fail(e.Line, "unknown class "+e.Text)
		}
		if g.execution {
			return "NewContext_" + name(e.Text) + "(execution," + args(e.Args) + ")"
		}
		return "New_" + name(e.Text) + "(" + args(e.Args) + ")"
	case "object_array_cast":
		return "rt.ObjectToArray(" + args(e.Args) + ")"
	case "property":
		return "(" + g.expr(e.Args[0], scope) + ").(interface{Get(string) any}).Get(" + strconv.Quote(e.Text) + ")"
	case "method":
		n := name(e.Text)
		if !g.methods[n] {
			g.fail(e.Line, "unknown method "+n)
		}
		if g.execution {
			return "(" + g.expr(e.Args[0], scope) + ").(interface{MContext_" + n + "(*rt.Execution,...any) any}).MContext_" + n + "(execution," + args(e.Args[1:]) + ")"
		}
		return "(" + g.expr(e.Args[0], scope) + ").(interface{M_" + n + "(...any) any}).M_" + n + "(" + args(e.Args[1:]) + ")"
	}
	g.fail(e.Line, "unsupported IR expression "+e.Kind)
	return ""
}
